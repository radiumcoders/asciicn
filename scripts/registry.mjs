// registry.json is the only list of components. This checks every item has
// its source, demo and docs page, then writes the demo map the site imports.
import { existsSync, readFileSync, writeFileSync } from "node:fs"

const registry = JSON.parse(readFileSync("registry.json", "utf8"))
const problems = []

for (const item of registry.items) {
  const expected = [
    ...item.files.map((file) => file.path),
    `registry/${item.name}/demo.tsx`,
    `content/docs/components/${item.name}.mdx`,
  ]
  for (const path of expected) {
    if (!existsSync(path)) problems.push(`${item.name}: missing ${path}`)
  }
  const page = `content/docs/components/${item.name}.mdx`
  if (existsSync(page) && !readFileSync(page, "utf8").includes(`title: ${item.title}\n`)) {
    problems.push(`${item.name}: ${page} title should be "${item.title}"`)
  }
}

if (problems.length) {
  console.error(problems.join("\n"))
  process.exit(1)
}

const entries = registry.items
  .map((item) => `  "${item.name}": () => import("./${item.name}/demo") as Promise<DemoModule>,`)
  .join("\n")

writeFileSync(
  "registry/demos.tsx",
  `// Generated by scripts/registry.mjs from registry.json. Do not edit.
"use client"

import type { DemoModule } from "@/lib/controls"

// Each demo loads on demand, with its live controls.
export const demos: Record<string, () => Promise<DemoModule>> = {
${entries}
}
`
)

console.log(`registry: ${registry.items.length} items`)
